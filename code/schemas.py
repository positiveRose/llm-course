"""Схемы и промпты, которые уже собраны в уроках 01–03 и дальше используются как готовые детали."""

from typing import Literal

from pydantic import BaseModel, Field

from common import load_kb


class Route(BaseModel):  # урок 02, блок 1
    category: Literal["billing", "tech", "general"]


class TicketFields(BaseModel):  # урок 02, блок 2
    order_id: int | None = Field(description="Номер заказа из текста. null, если номера в тексте нет")
    product: str | None = Field(description="Товар, о котором пишет клиент, одним-двумя словами. null, если товара нет")
    days_ago: int | None = Field(
        description="Сколько дней назад произошло событие, о котором пишет клиент: покупка, получение, возврат, отмена. "
        "Неделя это 7, месяц это 30. null, если клиент не сказал, сколько дней назад это было"
    )


class Triage(TicketFields):  # урок 03: поля из урока 02 плюс признак для гейта
    needs_order: bool = Field(
        description="true, если клиент пишет о своём конкретном заказе или платеже и без номера заказа его вопрос не решить. "
        "false, если он спрашивает о правилах магазина"
    )


class Verdict(BaseModel):  # урок 03: вердикт судьи о черновике ответа
    reasoning: str = Field(description="Что в ответе соответствует базе знаний, а что нет, в двух-трёх предложениях")
    passed: bool  # стоит после reasoning: вердикт опирается на разбор, а не наоборот
    feedback: str = Field(description="Что исправить в ответе. Пустая строка, если passed равно true")


class Ranking(BaseModel):  # урок 07: реранкер возвращает порядок номеров, а не тексты
    order: list[int] = Field(description="Номера фрагментов от самого полезного к самому бесполезному, без пропусков и повторов")


class Finding(BaseModel):  # урок 12: что сабагент возвращает оркестратору вместо журнала своих шагов
    facts: str = Field(description="Что выяснили: данные заказа и правило из базы знаний, одним-двумя предложениями")
    refund: bool = Field(description="true, если клиент просит вернуть деньги и возврат положен по правилам")
    order_id: int | None = Field(description="Номер заказа для возврата. null, если refund равно false")
    amount_rub: int | None = Field(description="Сумма возврата в рублях. null, если refund равно false")
    reply: str = Field(description="Что ответить клиенту по этой проблеме, одно-два предложения")


class Review(BaseModel):  # урок 12: вердикт проверяющего о предложенном возврате
    reasoning: str = Field(description="Что в решении сходится с обращением, заказом и правилами, а что нет, в двух-трёх предложениях")
    approve: bool  # после reasoning, как passed в Verdict


